#!/usr/bin/env python3
"""Copy the Codex race assets the game uses and write data/blippi-race-data.js (GENERATED; routes are authored by hand in data/blippi-race-routes.js).
 - vehicles: only families with status owner-supplied-review (15 paired: standard + blippi_peek x 5 views). The 7 construction families
   are 'needs-standard-pair' (no 30/70 swap allowed) and are NOT offered; they are listed in data as blocked.
 - arenas: the exact derivative named in racing-arena-manifest.json for each orientation (+ thumbnail). sha256 checked."""
import hashlib, importlib.util, json, os, shutil
PACK = '/home/baguspermana7/Documents/temporary/blippi/sudah organized/'
AR = '/home/baguspermana7/Documents/temporary/blippi/kekurangan/racing-arenas/'
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sha = lambda p: hashlib.sha256(open(p, 'rb').read()).hexdigest()
import sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from sliver import strip_slivers
stripped = {}
VIEWS = ['front', 'front-three-quarter', 'side', 'rear-three-quarter', 'rear']
T = json.load(open(PACK + 'database/vehicle-turnarounds.json'))
out = {'peek': T['race_peek_contract'], 'vehicles': [], 'blocked': [], 'arenas': [], 'views': VIEWS, 'angles': T['direction_contract']['logical_angles_degrees']}
for v in T['vehicles']:
    if v['status'] != 'owner-supplied-review':
        out['blocked'].append({'id': v['id'], 'category': v['category'], 'why': v['status']}); continue
    d = os.path.join(ROOT, 'assets/race', v['id']); os.makedirs(d, exist_ok=True)
    rec = {'id': v['id'], 'category': v['category'], 'mirror': 'approved-by-eye-2026-10-10', 'box': {}, 'anchor': {k: [o['anchor']['x'], o['anchor']['y'], o['anchor']['semantic']] for k, o in v['registration']['orientations'].items()}}
    for vw in VIEWS:
        rec['box'][vw] = [v['registration']['orientations'][vw]['render_box']['width'], v['registration']['orientations'][vw]['render_box']['height']]
        for st in ('standard', 'blippi_peek'):
            rec_ = v['states'][st][vw]
            src = PACK + rec_['file']
            assert sha(src) == rec_['sha256'], src
            dst = os.path.join(d, st + '-' + vw + '.webp')
            shutil.copyfile(src, dst)
            r = strip_slivers(dst)
            if r: stripped[v['id'] + '/' + st + '-' + vw] = r
    out['vehicles'].append(rec)
M = json.load(open(AR + 'racing-arena-manifest.json'))
os.makedirs(os.path.join(ROOT, 'assets/arena'), exist_ok=True)
for a in M['arenas']:
    rec = {'id': a['id'], 'surface': a['surface'], 'difficulty': a['difficulty'], 'modes': a['modes'], 'status': a['status']}
    for ori in ('landscape', 'portrait'):
        v = a['variants'][ori]
        src = AR + v['file']
        assert sha(src) == v['sha256'], src
        shutil.copyfile(src, os.path.join(ROOT, 'assets/arena/%s-%s.webp' % (a['id'], ori)))
        shutil.copyfile(AR + v['thumbnail'], os.path.join(ROOT, 'assets/arena/%s-%s-thumb.webp' % (a['id'], ori)))
        rec[ori] = [v['width'], v['height']]
    out['arenas'].append(rec)
open(os.path.join(ROOT, 'data/blippi-race-data.js'), 'w').write('/* GENERATED by tools/build-race-assets.py -- do not hand-edit. */\nwindow.BlippiRaceData = ' + json.dumps(out, indent=1) + '\n')
print('slivers stripped:', stripped)
print(len(out['vehicles']), 'vehicles,', len(out['blocked']), 'blocked,', len(out['arenas']), 'arenas')
