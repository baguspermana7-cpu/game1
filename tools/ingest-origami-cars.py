"""Cut the owner's Origami Cars pack into the game1 fleet 'mobilkertas' (MOBIL KERTAS arena, owner 2026-10-19).

Pack: Origami_Cars_25/characters/NN_<Slug>/ with
  <Slug>_Drive.gif     512x512, 64 frames at 20 fps (50 ms), rear view, binary alpha + baked speed streaks / paper flecks
  <Slug>_Preview.png   800x800 rear three-quarter still, full alpha (the selection picture)
Each GIF frame keeps only its largest alpha body (the streaks and flecks are separate specks; the land engine draws its
own dust and turbo), then every frame is cut to ONE box = the union of the bodies over all frames (nothing jitters)
and scaled so the car stands as tall as the DARAT fleet's. The GIF's binary edge is softened by the LANCZOS downscale.
Output: assets/fleet/mobilkertas/<id>.webp (play sheet, rows of 10) + <id>-tile.webp, data/blippi-fleet-mobilkertas.js.
Usage: ~/.venvs/kokoro/bin/python tools/ingest-origami-cars.py <dir holding Origami_Cars_25/>"""
import glob, json, os, re, sys
import numpy as np
from PIL import Image, ImageSequence
from scipy import ndimage

ROOT = sys.argv[1]
CHARS = sorted(glob.glob(os.path.join(ROOT, 'Origami_Cars_25', 'characters', '[0-9][0-9]_*')))
OUT = 'assets/fleet/mobilkertas'
TARGET_H = 150      # the DARAT play frames are ~146-149 px tall
TILE = 180
COLS = 10
NAMES = ['Mobil Polisi Kertas', 'Van SWAT Kertas', 'Taksi Kertas', 'Mobil Formula Kertas', 'Truk Pemadam Kertas', 'Ambulans Kertas',
         'Truk Sampah Kertas', 'Bus Sekolah Kertas', 'Bus Kota Kertas', 'Truk Derek Kertas', 'Truk Jungkit Kertas', 'Truk Molen Kertas',
         'Mobil Penyapu Kertas', 'Bajak Salju Kertas', 'Van Antar Kertas', 'Mobil Es Krim Kertas', 'Mobil Kemah Kertas',
         'Monster Truk Kertas', 'Mobil Bak Kertas', 'Mobil Klasik Kertas', 'Mobil Reli Kertas', 'Mobil Super Kertas',
         'Limosin Kertas', 'Traktor Kertas', 'Truk Makanan Kertas']


def slug_id(d):
    return re.sub(r'^\d+_', '', os.path.basename(d)).lower().replace('_', '-')


def body_only(rgba):
    """keep the largest connected alpha region (the car); drop streaks and flecks"""
    a = rgba[:, :, 3] > 40
    lab, n = ndimage.label(a)
    if n == 0:
        return rgba
    sizes = ndimage.sum(a, lab, range(1, n + 1))
    keep = lab == (int(np.argmax(sizes)) + 1)
    keep = ndimage.binary_closing(keep, iterations=2) & (rgba[:, :, 3] > 0)
    out = rgba.copy()
    out[:, :, 3] = np.where(keep, rgba[:, :, 3], 0)
    return out


def frames_of(gif):
    im = Image.open(gif)
    return [body_only(np.array(f.convert('RGBA'))) for f in ImageSequence.Iterator(im)]


def union_box(frames):
    m = np.zeros(frames[0].shape[:2], bool)
    for f in frames:
        m |= f[:, :, 3] > 0
    ys, xs = np.where(m)
    return xs.min(), ys.min(), xs.max() + 1, ys.max() + 1


def save_sheet(frames, path):
    x0, y0, x1, y1 = union_box(frames)
    s = TARGET_H / float(y1 - y0)
    fw, fh = int(round((x1 - x0) * s)) + 4, int(round((y1 - y0) * s)) + 4
    rows = (len(frames) + COLS - 1) // COLS
    sheet = Image.new('RGBA', (fw * COLS, fh * rows), (0, 0, 0, 0))
    for i, f in enumerate(frames):
        im = Image.fromarray(f).crop((x0, y0, x1, y1))
        # premultiplied resize so the transparent pixels' colour never bleeds into the soft edge
        im = im.convert('RGBa').resize((fw - 4, fh - 4), Image.LANCZOS).convert('RGBA')
        sheet.paste(im, ((i % COLS) * fw + 2, (i // COLS) * fh + 2))
    sheet.save(path, quality=86, method=4)
    return [fw, fh, len(frames), COLS]


def save_tile(png, path):
    im = Image.open(png).convert('RGBA')
    im = im.crop(im.getbbox())
    k = TILE / float(max(im.size))
    im = im.convert('RGBa').resize((max(1, int(im.width * k)), max(1, int(im.height * k))), Image.LANCZOS).convert('RGBA')
    t = Image.new('RGBA', (im.width + 8, im.height + 8), (0, 0, 0, 0))
    t.paste(im, (4, 4))
    t.save(path, quality=88, method=4)
    return [t.width, t.height]


os.makedirs(OUT, exist_ok=True)
items = []
for n, d in enumerate(CHARS):
    vid = slug_id(d)
    gif = glob.glob(os.path.join(d, '*_Drive.gif'))[0]
    prev = glob.glob(os.path.join(d, '*_Preview.png'))[0]
    play = save_sheet(frames_of(gif), '%s/%s.webp' % (OUT, vid))
    tile = save_tile(prev, '%s/%s-tile.webp' % (OUT, vid))
    items.append({'id': vid, 'name': NAMES[n] if n < len(NAMES) else vid, 'play': play, 'tile': tile})
    print(vid, play, tile)
js = ('/* G32 Blippi -- the MOBIL KERTAS fleet (generated by tools/ingest-origami-cars.py from the owner\'s Origami Cars pack; do\n'
      ' * not hand-edit). play = rear-view frame sheet [frameW, frameH, frames, columns] at frameMs; tile = the diagonal still. */\n'
      'window.BlippiFleet = window.BlippiFleet || {}\n'
      'window.BlippiFleet["mobilkertas"] = { frameMs: 50, items: %s }\n') % json.dumps(items, indent=1)
open('data/blippi-fleet-mobilkertas.js', 'w').write(js)
print('fleet', len(items))
