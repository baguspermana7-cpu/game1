#!/usr/bin/env python3
"""Copy the child-safe, licence-cleared owner VFX that game1 uses into assets/vfx/ and write data/blippi-vfx.js
(id, file, source, license, credit, blend). Source: uiux/visual effect/sudah organized/database/blippi-safe.json."""
import json, os, shutil
SRC = '/home/baguspermana7/Documents/temporary/uiux/visual effect/sudah organized'
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
USE = {  # our name -> file basename in blippi-safe.json
  'confetti': 'blippi-discovery-game-effects-collection--confetti-burst.webp',
  'check-burst': 'preschool-adventure-effects-sprite-sheet--blue-check-burst.webp',
  'gold-star': 'preschool-adventure-effects-sprite-sheet--gold-starburst.webp',
  'splash': 'blippi-discovery-game-effects-collection--water-splash-crown.webp',
  'droplets': 'blippi-discovery-game-effects-collection--water-droplets.webp',
  'bubbles': 'preschool-adventure-effects-sprite-sheet--bubbles.webp',
  'ripple': 'blippi-discovery-game-effects-collection--water-ripple.webp',
  'cloud': 'preschool-adventure-effects-sprite-sheet--soft-cloud.webp',
  'dust': 'preschool-adventure-effects-sprite-sheet--dust-puff.webp',
  'speed': 'preschool-adventure-effects-sprite-sheet--speed-streaks.webp',
  'spark': 'preschool-adventure-effects-sprite-sheet--bright-spark-burst.webp',
  'leaves': 'blippi-discovery-game-effects-collection--flying-leaves.webp',
  'rays': 'preschool-adventure-effects-sprite-sheet--light-rays.webp',
  'rainbow': 'preschool-adventure-effects-sprite-sheet--rainbow.webp',
}
items = {os.path.basename(e['file']): e for e in json.load(open(SRC + '/database/blippi-safe.json'))['effects']}
os.makedirs(ROOT + '/assets/vfx', exist_ok=True)
out = {}
for name, base in USE.items():
    e = items[base]
    assert e.get('blippi_safe') and e['status'] == 'ready', name
    shutil.copyfile(SRC + '/' + e['file'], ROOT + '/assets/vfx/' + name + '.webp')
    lic = e['license'] if isinstance(e.get('license'), dict) else {}
    out[name] = {'file': 'assets/vfx/%s.webp' % name, 'id': e['id'], 'source': e['source'], 'license': lic.get('status') or e.get('license_safe'),
                 'credit': lic.get('credit') or '', 'blend': e['blend_mode'], 'w': e['width'], 'h': e['height']}
js = '/* generated by tools/build-vfx.py from blippi-safe.json -- do not hand-edit. id/source/licence/credit kept per effect. */\nwindow.BlippiVFX = ' + json.dumps(out, indent=1) + '\n'
open(ROOT + '/data/blippi-vfx.js', 'w').write(js)
print(len(out), 'effects')
