"""BALAP PESAWAT racers from the owner's Planes pack (2026-10-18) -> fleet 'balap'.

The pack (Planes_25_Animated_Pack.zip), per character:
  characters/NN_Name/<Name>_12_Poses.png   2048 x 1536, 4 x 3 cells of 512, transparent with smooth alpha:
                                           row 1 Straight, row 2 Left (banking left), row 3 Right; 4 propeller /
                                           jet phases each, no wind effects   <- the source used here
  characters/NN_Name/<Name>_Preview.png    800 x 800 rear-diagonal still, transparent   <- the card tile
  (the GIFs carry the wind lines on BINARY alpha -- speckled edges -- so they are not used; the arena draws its own
   speed wisps, and the engine blends one phase into the next, so 4 drawn phases play as a continuous spin)

Output (game1 root), the same shape as tools/ingest-fleet.py so the trip engine needs nothing new:
  assets/fleet/balap/<id>.webp         straight: 4 cells in one row, every cell the SAME box (the union of the
                                       alpha of all 12 poses), so a view change never moves the plane
  assets/fleet/balap/<id>-left.webp    banking left, same box
  assets/fleet/balap/<id>-right.webp   banking right, same box
  assets/fleet/balap/<id>-tile.webp    the trimmed preview for the cards
  data/blippi-fleet-balap.js           window.BlippiFleet.balap = { frameMs, items: [{ id, name, play, tile, views }] }

  python3 tools/ingest-planes.py <extracted pack dir>      (needs numpy + Pillow: ~/.venvs/kokoro/bin/python)
"""
import glob, json, os, re, sys
import numpy as np
from PIL import Image

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
OUT = os.path.join(ROOT, 'assets', 'fleet', 'balap')
JS = os.path.join(ROOT, 'data', 'blippi-fleet-balap.js')
VIEWS = ('straight', 'left', 'right')
MAX = 240        # the plane is drawn ~1.3 x the lane size (~110 px on a phone): 240 px cells stay sharp at 2x DPR
FRAME_MS = 70    # one propeller phase; the engine crossfades into the next, so the spin never ticks


def slug(name):
    return re.sub(r'[^a-z0-9]+', '-', name.lower()).strip('-')


def main(pack):
    os.makedirs(OUT, exist_ok=True)
    items = []
    for folder in sorted(glob.glob(os.path.join(pack, 'characters', '*'))):
        man = json.load(open(os.path.join(folder, 'manifest.json')))
        cs, cols = man.get('cell_size', 512), man['pose_sheet']['columns']
        rid = slug(man['name'])
        sheet = Image.open(os.path.join(folder, man['poses'])).convert('RGBA')
        cells = {v: [sheet.crop((c * cs, i * cs, (c + 1) * cs, (i + 1) * cs)) for c in range(cols)] for i, v in enumerate(VIEWS)}
        alpha = np.stack([np.array(f)[..., 3] for v in VIEWS for f in cells[v]]).max(0)
        ys, xs = np.where(alpha > 10)
        # a square box centred on the union (the engine fits a cell into a square around the plane's centre)
        cx, cy = (xs.min() + xs.max() + 1) / 2, (ys.min() + ys.max() + 1) / 2
        half = max(xs.max() + 1 - xs.min(), ys.max() + 1 - ys.min()) / 2 + 4
        box = (int(round(cx - half)), int(round(cy - half)), int(round(cx + half)), int(round(cy + half)))
        side = box[2] - box[0]
        fw = min(MAX, side)
        for v in VIEWS:
            out = Image.new('RGBA', (fw * cols, fw), (0, 0, 0, 0))
            for j, f in enumerate(cells[v]):
                out.alpha_composite(f.crop(box).resize((fw, fw), Image.LANCZOS), (j * fw, 0))
            out.save(os.path.join(OUT, rid + ('' if v == 'straight' else '-' + v) + '.webp'), quality=88, method=6)
        pv = Image.open(os.path.join(folder, man['preview'])).convert('RGBA')
        pv = pv.crop(pv.getchannel('A').point(lambda a: 255 if a > 10 else 0).getbbox())
        pv.thumbnail((260, 260), Image.LANCZOS)
        pv.save(os.path.join(OUT, rid + '-tile.webp'), quality=88, method=6)
        items.append({'id': rid, 'name': man['name'], 'play': [fw, fw, cols, cols], 'tile': [pv.width, pv.height], 'views': 1})
        print(rid, fw, pv.size)
    open(JS, 'w').write('/* G32 Blippi -- the BALAP PESAWAT fleet (generated by tools/ingest-planes.py from the owner\'s Planes pack; do not\n'
                        ' * hand-edit). play = straight rear-view phases [frameW, frameH, frames, columns] at frameMs; views = the same\n'
                        ' * phases banking left / right in <id>-left / <id>-right; tile = the diagonal still for selection. */\n'
                        'window.BlippiFleet = window.BlippiFleet || {}\n'
                        'window.BlippiFleet["balap"] = { frameMs: %d, items: %s }\n' % (FRAME_MS, json.dumps(items, indent=1, ensure_ascii=False)))
    print(len(items), 'planes ->', os.path.relpath(JS, ROOT))


if __name__ == '__main__':
    main(sys.argv[1])
