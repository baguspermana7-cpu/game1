import json
from PIL import Image
j=json.load(open('data/blippi-race-data.js'.replace('','')) if False else open('/dev/null')) if False else None
s=open('data/blippi-race-data.js').read(); j=json.loads(s[s.index('{'):s.rindex('}')+1]); V=j['views']
for v in j['vehicles']:
    for vw in V: v['box'][vw]=list(Image.open(f"assets/race/{v['id']}/standard-{vw}.webp").size)
open('data/blippi-race-data.js','w').write('/* GENERATED by tools/build-race-assets.py then tools/recrop-vehicles.py (box = recropped alpha size) */\nwindow.BlippiRaceData = '+json.dumps(j,indent=1)+'\n')
ids=[v['id'] for v in j['vehicles']]
S=104
sheet=Image.new('RGB',(S*13,S*len(ids)),(0,0,0))
for r_,i in enumerate(ids):
    for c,(st,vw) in enumerate([(a,b) for a in('standard','blippi_peek') for b in V]):
        bg=Image.new('RGB',(S,S))
        for y in range(0,S,13):
            for x in range(0,S,13): bg.paste((205,205,205) if (x//13+y//13)%2 else (150,150,150),(x,y,x+13,y+13))
        im=Image.open(f'assets/race/{i}/{st}-{vw}.webp').convert('RGBA'); im.thumbnail((S-4,S-4)); bg.paste(im,(2,2),im); sheet.paste(bg,(c*S,r_*S))
for k,vw in enumerate(['front','three-quarter','rear']):
    bg=Image.new('RGB',(S,S),(150,150,150)); im=Image.open(f'assets/blippi/driver-{vw}.webp').convert('RGBA'); im.thumbnail((S-4,S-4)); bg.paste(im,(2,2),im); sheet.paste(bg,(10*S+k*S,0))
sheet.save('docs/sheets/vehicle-crop-audit.png')
